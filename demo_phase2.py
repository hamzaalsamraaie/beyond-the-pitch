"""
Phase 2 demonstration script.

⚠️  DEMONSTRATION ONLY — ALL OUTPUT IS MOCK DATA ⚠️
This script uses MockResearchProvider and MockScriptWriter by default.
No API calls are made. The storyboard is NOT verified current news.
The research items are based on historical Wikipedia facts but have
NOT been independently fact-checked for this demonstration.

Usage:
    python demo_phase2.py                  # mock mode (no API key needed)
    python demo_phase2.py --use-claude     # real Claude API (requires ANTHROPIC_API_KEY)
    python demo_phase2.py --type player_stories
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
from pathlib import Path

# ── Make sure project root is on the path ─────────────────────────────────────
sys.path.insert(0, str(Path(__file__).parent))

from dotenv import load_dotenv

load_dotenv()

import src.core.database as db_module
from src.core.database import init_db
from src.core.kill_switch import disarm
from src.core.logger import configure_logging
from src.research.models import ContentType
from src.research.pipeline import StoryboardPipeline
from src.research.providers import MockResearchProvider
from src.research.script_writer import ClaudeScriptWriter, MockScriptWriter


def _parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Phase 2 storyboard demonstration")
    p.add_argument(
        "--use-claude",
        action="store_true",
        help="Use the real Claude API (requires ANTHROPIC_API_KEY in .env)",
    )
    p.add_argument(
        "--type",
        choices=["football_moments", "player_stories", "football_motivation", "all"],
        default="all",
        help="Content type to generate (default: all)",
    )
    return p.parse_args()


def _print_storyboard(sb, demo_label: str) -> None:
    print("\n" + "=" * 72)
    print(f"  {demo_label}")
    print("=" * 72)
    print(f"  Title:          {sb.title}")
    print(f"  Content type:   {sb.content_type.value}")
    print(f"  Duration:       {sb.total_duration}s")
    print(f"  Scenes:         {len(sb.scenes)}")
    print(f"  Generated by:   {sb.generated_by}")
    print(f"  Script hash:    {sb.script_hash[:16]}...")
    print()
    print("  Hook:", sb.hook)
    print()
    print("  ── Scenes ──")
    for scene in sb.scenes:
        print(f"  Scene {scene.scene_number}  [{scene.start_time:.1f}s → {scene.end_time:.1f}s]")
        print(f"    On-screen:  {scene.on_screen_text}")
        print(f"    Narration:  {scene.narration[:120]}{'...' if len(scene.narration) > 120 else ''}")
        print(f"    Visual:     {scene.visual_requirement}")
        sources = [sb.research_items[i].source.title for i in scene.source_indices]
        print(f"    Sources:    {', '.join(sources)}")
        print()

    print("  ── Proposed YouTube Titles ──")
    for i, t in enumerate(sb.proposed_titles, 1):
        print(f"    {i}. {t}")

    print()
    print("  ── Hashtags ──")
    print("    " + "  ".join(sb.hashtags))

    print()
    print("  ── Source Citations ──")
    for i, item in enumerate(sb.research_items):
        print(f"    [{i}] {item.source.title}")
        print(f"        {item.source.url}")
        print(f"        reliability: {item.reliability}")

    print()
    print("  ── Score Breakdown (from pipeline ranking) ──")
    print("  (scores are from MockResearchProvider fixture data)")

    print("=" * 72)


def main() -> None:
    args = _parse_args()
    configure_logging()

    # Use a temporary DB so the demo doesn't pollute the real database
    tmp_db = tempfile.mktemp(suffix="_demo.db")
    db_module.DB_PATH = Path(tmp_db)
    init_db()
    disarm()

    print()
    print("┌─────────────────────────────────────────────────────────────────┐")
    print("│  BEYOND THE PITCH — Phase 2 Demonstration                       │")
    print("│                                                                   │")
    print("│  ⚠  ALL OUTPUT BELOW IS MOCK / DEMONSTRATION DATA               │")
    print("│  ⚠  NOT VERIFIED CURRENT NEWS — NOT FOR PUBLICATION             │")
    print("│  ⚠  Research items are from Wikipedia (historical facts only)   │")
    print("└─────────────────────────────────────────────────────────────────┘")

    # Choose writer
    if args.use_claude:
        api_key = os.environ.get("ANTHROPIC_API_KEY", "")
        if not api_key:
            print("\nERROR: --use-claude requires ANTHROPIC_API_KEY to be set in .env")
            sys.exit(1)
        print(f"\n  Using REAL Claude API — charges will apply.")
        writer = ClaudeScriptWriter()
    else:
        print(f"\n  Using MockScriptWriter — zero cost, no API calls.")
        writer = MockScriptWriter()

    # Choose content types
    if args.type == "all":
        types = [
            ContentType.FOOTBALL_MOMENTS,
            ContentType.PLAYER_STORIES,
            ContentType.FOOTBALL_MOTIVATION,
        ]
    else:
        types = [ContentType(args.type)]

    pipeline = StoryboardPipeline(
        provider=MockResearchProvider(),
        writer=writer,
        min_score_threshold=0.0,  # accept everything in demo
    )

    print(f"\n  Generating storyboards for: {[t.value for t in types]}")
    storyboards = pipeline.run(content_types=types)

    if not storyboards:
        print("\n  No storyboards generated. Check logs for details.")
        return

    for sb in storyboards:
        _print_storyboard(
            sb,
            demo_label=f"DEMO STORYBOARD — {sb.content_type.value.upper()} (MOCK DATA)",
        )

    # Save JSON to output/
    output_dir = Path(__file__).parent / "output"
    output_dir.mkdir(exist_ok=True)
    for sb in storyboards:
        slug = sb.content_type.value
        out_path = output_dir / f"demo_storyboard_{slug}.json"
        out_path.write_text(sb.to_json(indent=2), encoding="utf-8")
        print(f"\n  JSON saved: {out_path}")

    # Cleanup temp DB
    Path(tmp_db).unlink(missing_ok=True)

    print()
    print("  Demo complete. No videos were rendered or uploaded.")
    print()


if __name__ == "__main__":
    main()

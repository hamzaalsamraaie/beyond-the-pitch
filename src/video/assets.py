@dataclass
class AssetEntry:
    asset_id: str
    asset_type: str               # font | image | audio | background
    name: str
    source_url: str               # "system" for OS-provided assets
    license: str                  # e.g. "system_font", "OFL-1.1", "CC0", "original"
    permitted_uses: list[str]     # e.g. ["commercial", "educational", "broadcast"]
    attribution_required: bool
    attribution_text: str = ""    # only needed if attribution_required=True
    authorization_evidence: str = ""
    local_path: str = ""          # path on disk if downloaded



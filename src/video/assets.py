class AssetManifest:
    """
    Tracks all assets used in production.
    Persisted as JSON at data/asset_manifest.json.
    """

    def __init__(self, manifest_path: Optional[Path] = None) -> None:
        cfg = get_section("production")
        default_path = _PROJECT_ROOT / cfg.get("asset_manifest_path", "data/asset_manifest.json")
        self._path = manifest_path or default_path
        self._entries: dict[str, AssetEntry] = {}
        self._load_or_init()

    def _load_or_init(self) -> None:
        if self._path.exists():
            try:
                with open(self._path, "r", encoding="utf-8") as fh:
                    data = json.load(fh)
                for entry_data in data.get("assets", []):
                    e = AssetEntry(**entry_data)
                    self._entries[e.asset_id] = e
                logger.info("asset_manifest_loaded", path=str(self._path), count=len(self._entries))
            except Exception as exc:
                logger.warning("asset_manifest_load_failed", error=str(exc))
                self._seed_builtins()
        else:
            self._seed_builtins()

    def _seed_builtins(self) -> None:
        for entry in _BUILTIN_ASSETS:
            self._entries[entry.asset_id] = entry
        self._save()

    def _save(self) -> None:
        self._path.parent.mkdir(parents=True, exist_ok=True)
        payload = {"assets": [asdict(e) for e in self._entries.values()]}
        with open(self._path, "w", encoding="utf-8") as fh:
            json.dump(payload, fh, indent=2)

    def get(self, asset_id: str) -> Optional[AssetEntry]:
        return self._entries.get(asset_id)

    def register(self, entry: AssetEntry) -> None:
        self._entries[entry.asset_id] = entry
        self._save()
        logger.info("asset_registered", asset_id=entry.asset_id, license=entry.license)

    def verify_permitted(self, asset_id: str, use: str) -> bool:
        """Return True if the asset permits the given use category."""
        entry = self.get(asset_id)
        if not entry:
            return False
        return use in entry.permitted_uses

    def all_entries(self) -> list[AssetEntry]:
        return list(self._entries.values())

    def get_font_path(self, font_id: str) -> Path:
        """Return the font path for a registered font asset, or raise."""
        entry = self.get(font_id)
        if not entry or entry.asset_type != "font":
            raise KeyError(f"No font asset registered with id '{font_id}'")
        path = Path(entry.local_path)
        if not path.exists():
            raise FileNotFoundError(f"Font file not found: {path}")
        return path

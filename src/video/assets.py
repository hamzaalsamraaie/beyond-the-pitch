"""
Asset manifest manager.

Every asset used in production (fonts, images, audio, backgrounds) must be
registered here with:
  - source_url: where the asset came from
  - license: the license type (e.g. "system_font", "OFL-1.1", "CC0", "original")
  - permitted_uses: list of permitted use categories
  - attribution_required: whether attribution must appear in the video
  - authorization_evidence: how authorization was obtained

Phase 3 uses only:
  - macOS system fonts (available for use in macOS applications)
  - Programmatically generated gradients (original work, no license needed)
  - FFmpeg-generated silence audio (no license)

IMPORTANT: Never add an asset with license="assumed" or authorization_evidence="public".
Publicly accessible ≠ licensed. Each entry must be verified.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, asdict
from pathlib import Path
from typing import Optional

from src.core.config import get_section
from src.core.logger import get_logger


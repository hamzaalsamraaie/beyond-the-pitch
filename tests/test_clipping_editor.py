"""
Integration tests for ClipEditor.

These tests use a fixture video generated by FFmpeg lavfi (no real footage needed).
The gate is bypassed with bypass_gate=True so no footage catalog entry is required.
"""

import subprocess
import shutil
import pytest
from pathlib import Path

from src.clipping.editor import ClipEditor
from src.clipping.models import ClipSpec
from src.clipping.transcriber import MockTranscriber
from src.core.database import init_db


pytestmark = pytest.mark.skipif(
    shutil.which("ffmpeg") is None,
    reason="ffmpeg not found on PATH",
)


def _make_test_video(path: Path, duration: float = 5.0):
    """Create a synthetic test video using FFmpeg lavfi."""
    result = subprocess.run(
        [
            "ffmpeg", "-y",
            "-f", "lavfi",
            "-i", f"testsrc=size=1920x1080:rate=30:duration={duration}",
            "-f", "lavfi",
            "-i", f"sine=frequency=440:duration={duration}",
            "-c:v", "libx264", "-preset", "ultrafast", "-crf", "35",
            "-c:a", "aac", "-b:a", "64k",
            "-t", str(duration),
            str(path),
        ],
        capture_output=True,
    )
    return result.returncode == 0


def _make_clip(source: Path, duration: float = 5.0) -> ClipSpec:
    transcriber = MockTranscriber(mock_duration=duration)
    transcript = transcriber.transcribe(source)
    words = transcript.all_words[:20]  # limit to first 20 words
    return ClipSpec(
        source_path=source,
        footage_asset_id="test_fixture",
        start=0.0,
        end=duration,
        score=0.9,
        hook_text="incredible goal",
        transcript_words=words,
        language="en",
        crop_x_pct=0.5,
    )


def test_editor_produces_vertical_mp4(tmp_path):
    """Full end-to-end: fixture video → reframe → captions → audio → QC."""
    init_db()
    source = tmp_path / "source.mp4"
    output = tmp_path / "short.mp4"
    assert _make_test_video(source, duration=5.0)

    clip = _make_clip(source, duration=5.0)
    editor = ClipEditor(bypass_gate=True)
    result = editor.edit(clip, output_path=output)

    assert result.success, f"Edit failed: {result.failure_reason}"
    assert output.exists()
    assert output.stat().st_size > 5_000

    # Verify dimensions
    probe = subprocess.run(
        ["ffprobe", "-v", "quiet", "-select_streams", "v:0",
         "-show_entries", "stream=width,height",
         "-of", "csv=p=0", str(output)],
        capture_output=True, text=True,
    )
    w, h = probe.stdout.strip().split(",")
    assert int(w) == 1080
    assert int(h) == 1920


def test_editor_records_render_in_db(tmp_path):
    """render_id should be a positive integer after a successful edit."""
    init_db()
    source = tmp_path / "source2.mp4"
    _make_test_video(source, duration=4.0)
    clip = _make_clip(source, duration=4.0)

    editor = ClipEditor(bypass_gate=True)
    result = editor.edit(clip, output_path=tmp_path / "short2.mp4")
    assert result.render_id is not None
    assert isinstance(result.render_id, int)
    assert result.render_id > 0


def test_editor_missing_source_returns_failure(tmp_path):
    """Edit should fail gracefully when source file doesn't exist."""
    init_db()
    clip = ClipSpec(
        source_path=tmp_path / "nonexistent.mp4",
        footage_asset_id="test_fixture",
        start=0.0,
        end=5.0,
        score=0.5,
    )
    editor = ClipEditor(bypass_gate=True)
    result = editor.edit(clip)
    assert not result.success
    assert result.failure_reason
